a=float(input('Введите первое число: '))
b=float(input('Введите второе число: '))
print('Выберите операцию:')
print('1 - сложение')
print('2 - вычитание')
print('3 - умножение')
print('4 - деление')
o=int(input('Номер операции: '))
if o==1:
    print(f'Результат: {a+b:.3f}')
elif o==2:
    print(f'Результат: {a-b:.3f}')
elif o==3:
    print(f'Результат: {a*b:.3f}')
elif o==4:
    if b==0:
        print('Ошибка: деление на ноль!')
    else:
        print(f'Результат: {a/b:.3f}')
else:
    print('Ошибка: неверный номер операции')